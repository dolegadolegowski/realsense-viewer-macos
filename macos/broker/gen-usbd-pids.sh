#!/bin/bash
# Generates rs-usbd-pids.h, the Intel PIDs realsense-usbd accepts (DESIGN 2.4.1), from librealsense's D400/D500
# headers: every `const uint16_t <NAME>_PID = 0x<hex>;`, sorted and deduplicated. build-daemon.sh runs it.
#
#   gen-usbd-pids.sh <librealsense source dir> <output header>
#
# An output header that already has this content is left alone (its date decides what build-daemon.sh recompiles).
set -euo pipefail

SRC="${1:?usage: gen-usbd-pids.sh <librealsense source dir> <output header>}"
OUT="${2:?usage: gen-usbd-pids.sh <librealsense source dir> <output header>}"
HEADERS=("$SRC/src/ds/d400/d400-private.h" "$SRC/src/ds/d500/d500-private.h")

for h in "${HEADERS[@]}"; do
    [ -f "$h" ] || { echo "error: $h not found" >&2; exit 1; }
done

PIDS="$(sed -nE 's/^[[:space:]]*const[[:space:]]+uint16_t[[:space:]]+[A-Za-z0-9_]+_PID[[:space:]]*=[[:space:]]*0x([0-9A-Fa-f]{1,4})[[:space:]]*;.*$/\1/p' "${HEADERS[@]}" \
    | while read -r hex; do printf '0x%04x\n' "$((16#$hex))"; done | sort -u)"
COUNT="$(printf '%s\n' "$PIDS" | grep -c . || true)"
if [ "$COUNT" -lt 20 ]; then
    echo "error: found only $COUNT PIDs in the librealsense headers (expected at least 20)" >&2
    exit 1
fi

mkdir -p "$(dirname "$OUT")"
TMP="$(mktemp "$OUT.XXXXXX")"
{
    echo "// Generated by gen-usbd-pids.sh from librealsense's src/ds/d400/d400-private.h and"
    echo "// src/ds/d500/d500-private.h. Do not edit."
    echo "#pragma once"
    echo "#include <stdint.h>"
    echo "static const uint16_t RSUSBD_INTEL_PIDS[] = {"
    printf '%s\n' "$PIDS" | paste -sd, - | sed 's/,/, /g; s/^/    /'
    echo "};"
} > "$TMP"
if [ -f "$OUT" ] && cmp -s "$TMP" "$OUT"; then
    rm -f "$TMP"
else
    mv -f "$TMP" "$OUT"
fi
echo "$OUT: $COUNT PIDs"
